from pydantic import BaseModel, Field
from typing import Optional, Literal, List
from datetime import datetime

class WearableEventSubmission(BaseModel):
    event_id: str = Field(..., description="Unique UUID generated by device for idempotency")
    device_id: str = Field(..., description="ESP32 hardware device identifier")
    student_id: Optional[str] = None
    event_type: str = "HELP_REQUEST"
    request: Literal["I_NEED_HELP", "I_NEED_BREAK", "CANCEL", "ACKNOWLEDGE"]
    accessibility_mode: Literal["BLIND", "DEAF", "NON_SPEAKING"]
    timestamp: Optional[datetime] = None
    source: Literal["simulation", "hardware"] = "hardware"

class DeviceFeedback(BaseModel):
    vibration_pattern: str
    pattern_ms: List[int]
    led_color: str
    oled_text: str

class WearableEventResponse(BaseModel):
    success: bool
    status: str
    event_id: str
    feedback: Optional[DeviceFeedback] = None
    created_at: Optional[datetime] = None

class WearableStatusUpdate(BaseModel):
    status: Literal["Pending", "Acknowledged", "Assistance Provided", "Resolved", "Cancelled"]
    notes: Optional[str] = None
